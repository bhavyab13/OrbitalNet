// Inline docs/PROTOCOL.md and data/scenario.json into a TS module so the deployed bundle
// (Manufact Cloud) serves ocgp://protocol and mission defaults without the monorepo on disk.
import fs from "node:fs"; import path from "node:path";
const here = path.dirname(new URL(import.meta.url).pathname);
const pkg = path.resolve(here, ".."); const repo = path.resolve(pkg, "../..");
const protocol = fs.readFileSync(path.join(repo, "docs/PROTOCOL.md"), "utf8");
const scenario = fs.readFileSync(path.join(repo, "data/scenario.json"), "utf8");
fs.writeFileSync(path.join(pkg, "PROTOCOL.md"), protocol); fs.writeFileSync(path.join(pkg, "scenario.json"), scenario);
const out = `// GENERATED by scripts/gen-assets.mjs (npm run prepare-assets). Do not edit.\nexport const PROTOCOL_TEXT: string = ${JSON.stringify(protocol)};\nexport const SCENARIO: any = ${scenario.trim()};\n`;
fs.writeFileSync(path.join(pkg, "src/assets.gen.ts"), out);
console.log(`[gen-assets] protocol ${protocol.length} chars, scenario ${scenario.length} chars -> src/assets.gen.ts`);
